CREATE TABLE gold.fact_ticket (
    ticket_id text PRIMARY KEY CHECK (ticket_id ~ '^TKT-[0-9]+$'),
    building_key integer NOT NULL REFERENCES gold.dim_building (building_key),
    category_key integer NOT NULL REFERENCES gold.dim_category (category_key),
    priority_key integer NOT NULL REFERENCES gold.dim_priority (priority_key),
    status_key integer NOT NULL REFERENCES gold.dim_status (status_key),
    created_date date REFERENCES gold.dim_date (calendar_date),
    resolved_date date REFERENCES gold.dim_date (calendar_date),
    recorded_cost numeric(18,2) CHECK (recorded_cost >= 0),
    source_file_sha256 text NOT NULL,
    source_record_number bigint NOT NULL,
    FOREIGN KEY (source_file_sha256, source_record_number)
        REFERENCES bronze.raw_tickets (file_sha256, record_number)
);

CREATE VIEW gold.ticket_kpis AS
SELECT f.ticket_id, b.building_name AS building, c.category_name AS category,
       p.priority_name AS priority, s.status_name AS status, f.created_date, f.resolved_date,
       1 AS ticket_count,
       (s.is_terminal IS TRUE)::int AS terminal_count,
       (s.is_terminal IS FALSE)::int AS unresolved_count,
       (s.is_terminal IS NULL)::int AS unknown_status_count,
       (s.is_terminal IS FALSE AND p.priority_name = 'critical')::int AS critical_unresolved_count,
       f.recorded_cost, (f.recorded_cost IS NOT NULL)::int AS cost_count
FROM gold.fact_ticket f
JOIN gold.dim_building b USING (building_key)
JOIN gold.dim_category c USING (category_key)
JOIN gold.dim_priority p USING (priority_key)
JOIN gold.dim_status s USING (status_key);

CREATE VIEW gold.building_operations AS
SELECT building,
       SUM(ticket_count) AS total_tickets,
       SUM(terminal_count) AS terminal_tickets,
       SUM(unresolved_count) AS unresolved_tickets,
       SUM(unknown_status_count) AS unknown_status_tickets,
       SUM(critical_unresolved_count) AS critical_unresolved_tickets,
       SUM(cost_count) AS tickets_with_recorded_cost,
       SUM(recorded_cost) AS total_recorded_cost,
       AVG(recorded_cost) AS average_recorded_cost,
       100.0 * SUM(cost_count) / SUM(ticket_count) AS cost_coverage_pct,
       100.0 * SUM(terminal_count) / NULLIF(SUM(ticket_count) - SUM(unknown_status_count), 0) AS terminal_rate_pct
FROM gold.ticket_kpis
GROUP BY building;

